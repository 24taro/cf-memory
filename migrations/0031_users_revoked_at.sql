-- 招待の取り消しを可逆にする (2026-08-20)。
--
-- 取り消しは email を NULL にする実装だった。すると再招待は email で行を引けず、
-- 新しい行を作る —— 元の行とそこに紐づくノートが孤児になる。取り消して戻すだけで
-- その人の記憶が失われる形だった。
--
-- auth の users.disabled_at と同じ形にする: 行はそのまま、印だけ付ける。
-- 「まだ Access リストに居る人を止める」という同じ問題に、同じ答えを使う。
ALTER TABLE users ADD COLUMN revoked_at INTEGER;
