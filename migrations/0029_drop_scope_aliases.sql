-- scope_aliases を廃止 (2026-08-20)。1日も使われないまま消える。
--
-- 「この2つの文字列は同じプロジェクト」を人が登録する表だった。狙いは、複数
-- リポジトリにまたがるプロダクト(ShopApp)の記憶がどのリポジトリからも出るように
-- することと、本番で1つのプロジェクトが3通りに割れていた綴り揺れを畳むこと。
--
-- どちらも別の方法で解けた:
--   * 綴り揺れ  → scope を git remote に限った(0028 と normalizeScope)。値が
--                 揺れようがないので、畳む表が要らない。
--   * 複数リポジトリ → context を複数受けるようにした。親ディレクトリで作業すれば
--                 子リポジトリがまとめて対象になる。いるディレクトリが欲しい広さを
--                 表すので、登録する表が要らない。
--
-- 後者は前者より強い: 登録した組み合わせしか表現できない表と違い、任意の組み合わせを
-- `cd` だけで作れる。維持する対象が1つ減る方を採る。
DROP TABLE IF EXISTS scope_aliases;
